#!/usr/bin/env node
/**
 * WCAG contrast gate for the theme.
 *
 * Resolves the real `var()` chains from `tokens.css` — @theme ramps, `:root`
 * and `.dark` — through the same alias mapping the scaffold's app.config
 * declares (`primary: 'brand'`, `neutral: 'stone'`, …), then checks the pairs
 * the design system promises:
 *
 *   text on bg            >= 4.5   (normal text)
 *   highlighted on bg     >= 4.5
 *   primary as text on bg >= 4.5   (links)
 *   button: fg on primary >= 4.5   (white in light, ink in dark)
 *   primary vs bg         >= 3.0   (non-text: focus ring, control boundary)
 *
 * Both themes. Any failure exits 1.
 */
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(fileURLToPath(import.meta.url))
const css = readFileSync(path.join(root, '..', 'tokens.css'), 'utf8')

// Must match the `ui.colors` map emitted by `nuxt4:battlestack-theme`.
const ALIASES = { primary: 'brand', secondary: 'lilac', neutral: 'stone' }

/** All `--name: value` declarations inside the block opened by `selector`. */
function declarations(selector) {
    const start = css.indexOf(`${selector} {`)
    if (start === -1) throw new Error(`tokens.css: no "${selector}" block`)
    const body = css.slice(start, css.indexOf('}', start))
    const out = {}
    for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim()
    return out
}

const theme = declarations('@theme static')
const light = declarations(':root')
const dark = declarations('.dark')

// Nuxt UI defaults for names the theme does not override (subset we check).
const NUXT_UI_LIGHT = {
    '--ui-text-inverted': 'white',
}
const NUXT_UI_DARK = {
    '--ui-text-inverted': 'var(--ui-color-neutral-900)',
}

function resolve(name, vars, depth = 0) {
    if (depth > 12) throw new Error(`var chain too deep at ${name}`)
    // `--ui-color-<alias>-<shade>` is generated by Nuxt UI from the alias map.
    const alias = name.match(/^--ui-color-([a-z]+)-(\d+)$/)
    const value = alias
        ? `var(--color-${ALIASES[alias[1]] ?? alias[1]}-${alias[2]})`
        : (vars[name] ?? theme[name])
    if (!value) throw new Error(`unresolved token ${name}`)
    const ref = value.match(/^var\((--[\w-]+)\)$/)
    return ref ? resolve(ref[1], vars, depth + 1) : value
}

function srgb(hexOrKeyword) {
    const kw = { white: '#ffffff', black: '#000000' }
    const hex = (kw[hexOrKeyword] ?? hexOrKeyword).replace('#', '')
    const n = hex.length === 3 ? hex.split('').map((c) => c + c).join('') : hex
    return [0, 2, 4].map((i) => Number.parseInt(n.slice(i, i + 2), 16) / 255)
}

function luminance(color) {
    const [r, g, b] = srgb(color).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

function ratio(a, b) {
    const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
    return (hi + 0.05) / (lo + 0.05)
}

const failures = []
function check(themeName, vars, fgName, bgName, min, label) {
    const fg = resolve(fgName, vars)
    const bg = resolve(bgName, vars)
    const r = ratio(fg, bg)
    const ok = r >= min
    if (!ok) failures.push(`${themeName}: ${label} — ${fg} on ${bg} = ${r.toFixed(2)} (needs ${min})`)
    console.log(`${ok ? 'ok  ' : 'FAIL'} ${themeName.padEnd(5)} ${label.padEnd(28)} ${r.toFixed(2)} >= ${min}`)
}

for (const [themeName, vars] of [['light', { ...NUXT_UI_LIGHT, ...light }], ['dark', { ...NUXT_UI_DARK, ...light, ...dark }]]) {
    check(themeName, vars, '--ui-text', '--ui-bg', 4.5, 'body text on bg')
    check(themeName, vars, '--ui-text', '--ui-bg-muted', 4.5, 'body text on muted bg')
    check(themeName, vars, '--ui-text-highlighted', '--ui-bg', 4.5, 'headings on bg')
    check(themeName, vars, '--ui-primary', '--ui-bg', 4.5, 'primary as link text')
    check(themeName, vars, '--ui-text-inverted', '--ui-primary', 4.5, 'button label on primary')
    check(themeName, vars, '--ui-primary', '--ui-bg', 3.0, 'primary non-text vs bg')
}

if (failures.length > 0) {
    console.error(`\ncheck:contrast failed (${failures.length}):\n- ${failures.join('\n- ')}`)
    process.exit(1)
}
console.log('\ncheck:contrast passed')
